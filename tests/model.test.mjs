import assert from 'node:assert/strict';
import {assessText,makeWindows,aiProbabilityFromOutputs,combineWindows,runModel,MODEL_ID} from '../model.js';
const human='Yesterday, my brother and I went to the lake because the weather looked good. The bus was late and the picnic basket fell open on the pavement. We laughed, picked everything up, and carried on. It was a long day, and I went home exhausted. ';
const text=Array(7).fill(human).join('\n\n');
assert.equal(assessText('Hello world').ok,false);
assert.equal(assessText(text).ok,true);
assert.equal(assessText('你好 '.repeat(200)).ok,false);
const w=makeWindows(text);
assert.ok(w.length>=2&&w.length<=8);
assert.ok(w.every(x=>x.words<=180));
assert.equal(aiProbabilityFromOutputs([{label:'human',score:.8},{label:'ai',score:.2}]),.2);
assert.ok(Math.abs(aiProbabilityFromOutputs({label:'human',score:.3})-.7)<1e-9);
assert.throws(()=>aiProbabilityFromOutputs([{label:'unknown',score:.7}]),/Unknown model label/);
assert.deepEqual(combineWindows([{words:100,probability:.2},{words:100,probability:.8}]).score,50);
const calls=[];
const fake=async (piece,opt)=>{calls.push({piece,opt});return [{label:'human',score:.1},{label:'ai',score:.9}];};
const result=await runModel(text,{classifier:fake});
assert.equal(result.ok,true);assert.equal(result.score,90);assert.equal(result.modelId,MODEL_ID);
assert.ok(result.coverage>0);assert.equal(calls.length,result.windows.length);
assert.ok(calls.every(x=>x.opt.max_length===512&&x.opt.truncation===true));
assert.equal((await runModel('Too short',{classifier:fake})).ok,false);
const longText=Array(130).fill(human).join(' ');
const longer=await runModel(longText,{classifier:fake});
assert.ok(longer.coverage<1 && longer.windows.length===8,'long documents should show sampled coverage');
const fail=async()=>[{label:'POSITIVE',score:.9}];
await assert.rejects(runModel(text,{classifier:fail}),/Unknown model label/);
console.log('NoGPT v4 model contract tests passed (mock model only)');
